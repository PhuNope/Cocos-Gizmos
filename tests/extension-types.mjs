import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const extension = require('../main.js');
const projectRoot = mkdtempSync(path.join(os.tmpdir(), 'cocos-gizmos-project-'));
const assets = path.join(projectRoot, 'assets');
const previousEditor = globalThis.Editor;
try {
    mkdirSync(assets);
    const messages = [];
    globalThis.Editor = { Project: { path: projectRoot }, log: (s) => messages.push(s), warn: (s) => { throw new Error(s); } };
    extension.load();
    const bridge = path.join(assets, 'cocos-gizmos.global.d.ts');
    const content = readFileSync(bridge, 'utf8');
    assert.match(content, /^\/\/ AUTO-GENERATED by Cocos-Gizmos/);
    const relative = content.match(/<reference path="([^"]+)"/)[1];
    assert.equal(path.resolve(assets, relative), path.join(root, 'dist', 'Gizmos.d.ts'));
    // The editor integration must write actual, project-local ambient globals,
    // not just triple-slash references to extension files outside the project.
    assert.match(content, /declare const Gizmos2D: typeof import\(/);
    assert.match(content, /declare const Gizmos3D: typeof import\(/);
    assert.doesNotMatch(content, /^(?:import|export) /m);
    extension.load();
    assert.equal(readFileSync(bridge, 'utf8'), content, 'second load should be idempotent');

    const sample = path.join(assets, 'Consumer.ts');
    writeFileSync(sample, 'Gizmos2D.drawCircle(undefined as never, { x: 0, y: 0 }, 12);\nGizmos3D.drawSphere(undefined as never, undefined as never, 2);\n');
    const configPath = path.join(projectRoot, 'tsconfig.json');
    writeFileSync(configPath, JSON.stringify({
        compilerOptions: { target: 'ES2017', module: 'Node16', moduleResolution: 'Node16', skipLibCheck: true, noEmit: true, strict: true },
        include: ['assets/**/*']
    }));
    const config = ts.readConfigFile(configPath, ts.sys.readFile);
    assert.equal(config.error, undefined);
    const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, projectRoot);
    assert.equal(parsed.errors.length, 0);
    const program = ts.createProgram(parsed.fileNames, parsed.options);
    const diagnostics = ts.getPreEmitDiagnostics(program);
    assert.equal(diagnostics.length, 0, ts.formatDiagnosticsWithColorAndContext(diagnostics, {
        getCanonicalFileName: p => p, getCurrentDirectory: () => projectRoot, getNewLine: () => '\n'
    }));
    // TypeScript Language Service exercises prefix completion, not just
    // successful resolution of already-written Gizmos2D.drawCircle().
    const completionFile = path.join(assets, 'Completion.ts');
    const completionText = 'Gizmo';
    writeFileSync(completionFile, completionText);
    const scripts = [...parsed.fileNames, completionFile];
    const host = {
        getScriptFileNames: () => scripts,
        getScriptVersion: () => '0',
        getScriptSnapshot: fileName => {
            const text = ts.sys.readFile(fileName);
            return text === undefined ? undefined : ts.ScriptSnapshot.fromString(text);
        },
        getCurrentDirectory: () => projectRoot,
        getCompilationSettings: () => parsed.options,
        getDefaultLibFileName: ts.getDefaultLibFilePath,
        fileExists: ts.sys.fileExists,
        readFile: ts.sys.readFile,
        readDirectory: ts.sys.readDirectory,
    };
    const service = ts.createLanguageService(host, ts.createDocumentRegistry());
    try {
        const completion = service.getCompletionsAtPosition(completionFile, completionText.length, {});
        const names = new Set(completion?.entries.map(entry => entry.name));
        assert.ok(names.has('Gizmos2D'), 'TypeScript prefix completion is missing Gizmos2D');
        assert.ok(names.has('Gizmos3D'), 'TypeScript prefix completion is missing Gizmos3D');
    } finally {
        service.dispose();
    }
    console.log('[extension-types] global API resolves AND completes after typing Gizmo, with no imports');
} finally {
    if (previousEditor === undefined) delete globalThis.Editor;
    else globalThis.Editor = previousEditor;
    rmSync(projectRoot, { force: true, recursive: true });
}
