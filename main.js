'use strict';

const fs = require('node:fs');
const path = require('node:path');

const MARKER = '// AUTO-GENERATED by Cocos-Gizmos. Do not edit.\n';
const BRIDGE_NAME = 'cocos-gizmos.global.d.ts';

/**
 * Editor extensions live outside the Cocos project's TypeScript compilation.
 * A tiny reference file in assets/ makes the existing full declaration visible
 * to TypeScript/WebStorm without copying runtime JS or editing tsconfig.json.
 */
function installTypeBridge(projectRoot) {
    if (typeof projectRoot !== 'string' || !projectRoot.trim()) {
        throw new Error('Editor.Project.path is unavailable');
    }
    const declaration = path.join(__dirname, 'dist', 'Gizmos.d.ts');
    const assets = path.join(projectRoot, 'assets');
    const bridge = path.join(assets, BRIDGE_NAME);
    if (!fs.existsSync(declaration)) throw new Error('Missing dist/Gizmos.d.ts');
    if (!fs.statSync(assets).isDirectory()) throw new Error('Cocos project assets/ directory is unavailable');

    const target = path.relative(assets, declaration).split(path.sep).join('/');
    const escapedTarget = target.replaceAll('&', '&amp;').replaceAll('"', '&quot;');
    const text = MARKER + '/// <reference path="' + escapedTarget + '" />\n';

    if (fs.existsSync(bridge)) {
        const previous = fs.readFileSync(bridge, 'utf8');
        if (previous === text) return { updated: false, file: bridge };
        if (!previous.startsWith(MARKER)) {
            throw new Error('Refusing to overwrite an existing non-generated ' + bridge);
        }
    }
    fs.writeFileSync(bridge, text, 'utf8');
    return { updated: true, file: bridge };
}

exports.load = function load() {
    try {
        const result = installTypeBridge(globalThis.Editor?.Project?.path);
        if (result.updated) {
            globalThis.Editor?.log?.('[cocos-gizmos] Installed global types for TypeScript/WebStorm: ' + result.file);
        }
    } catch (error) {
        const message = '[cocos-gizmos] Could not register TypeScript globals: ' + error.message +
            '. If needed, add the installed extension dist/Gizmos.d.ts to your Cocos project tsconfig.json files/include.';
        if (globalThis.Editor?.warn) globalThis.Editor.warn(message);
        else console.warn(message);
    }
};

// Named export is used only by automated tests, not the editor API.
exports.installTypeBridge = installTypeBridge;
